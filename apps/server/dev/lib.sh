# Shared configuration and helpers for the plane-rs local dev stack.
#
# Source this file from the other dev scripts:
#
#   source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"
#
# When sourced it does not change shell options: the caller keeps responsibility
# for its own `set -euo pipefail`. Run directly, it fails fast.
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  set -euo pipefail
fi

# Repo layout. Everything is derived from this file's location so the scripts
# work from any working directory and from a worktree.
PLANE_DEV_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PLANE_SERVER_DIR="$(cd "$PLANE_DEV_DIR/.." && pwd)"
PLANE_REPO_ROOT="$(cd "$PLANE_SERVER_DIR/../.." && pwd)"
PLANE_API_DIR="$PLANE_REPO_ROOT/apps/api"
PLANE_DJANGO_PYTHON="$PLANE_API_DIR/.venv/bin/python"
PLANE_GUNICORN="$PLANE_API_DIR/.venv/bin/gunicorn"
PLANE_COMPOSE_FILE="$PLANE_DEV_DIR/compose.yml"
PLANE_COMPOSE_PROJECT="plane-rs-dev"
PLANE_DEV_ENV_FILE="$PLANE_DEV_DIR/.env.local"
PLANE_DEV_LOG_DIR="$PLANE_DEV_DIR/logs"
PLANE_DEV_RUN_DIR="$PLANE_DEV_DIR/run"

# Host ports, all bound to 127.0.0.1 by compose.yml. Keep in step with
# apps/server/AGENTS.md ("Dev stack").
PLANE_PG_HOST="127.0.0.1"
PLANE_PG_PORT="55432"
PLANE_PG_USER="plane"
PLANE_PG_PASSWORD="plane"
PLANE_VALKEY_HOST="127.0.0.1"
PLANE_VALKEY_PORT="56379"
PLANE_RABBITMQ_HOST="127.0.0.1"
PLANE_RABBITMQ_PORT="55672"
PLANE_RABBITMQ_MGMT_PORT="55673"
PLANE_RABBITMQ_USER="plane"
PLANE_RABBITMQ_PASSWORD="plane"
PLANE_MINIO_HOST="127.0.0.1"
PLANE_MINIO_PORT="59000"
PLANE_MINIO_CONSOLE_PORT="59090"
PLANE_MINIO_ACCESS_KEY="access-key"
PLANE_MINIO_SECRET_KEY="secret-key"
PLANE_MINIO_BUCKET="uploads"

# Per-session isolation knobs. Each concurrent agent picks its own database
# name (mkdb.sh), Redis DB index and RabbitMQ vhost (mq-vhost.sh). The defaults
# match the shared template built by bootstrap.sh.
PLANE_DB="${PLANE_DB:-plane}"
PLANE_REDIS_DB="${PLANE_REDIS_DB:-0}"
PLANE_MQ_VHOST="${PLANE_MQ_VHOST:-plane}"

# Filled in by bootstrap.sh; useful to scripts that print instructions.
PLANE_TEMPLATE_DB="plane_tpl"

# Load local secrets. The file is generated on first use, is gitignored, and
# currently only carries SECRET_KEY. It deliberately wins over the caller's
# environment so the template database and its encrypted instance configuration
# stay readable: changing SECRET_KEY invalidates encrypted values, so the
# template has to be rebuilt with `bootstrap.sh --force` if the key changes.
if [[ ! -f "$PLANE_DEV_ENV_FILE" ]]; then
  _plane_secret="$(python3 -c 'import secrets; print(secrets.token_urlsafe(50))')"
  (
    umask 077
    printf '%s\n' \
      '# Generated by apps/server/dev/lib.sh. Never commit this file.' \
      '# Used as Django SECRET_KEY for the local dev stack.' \
      "SECRET_KEY=${_plane_secret}" >"$PLANE_DEV_ENV_FILE"
  )
  unset _plane_secret
fi

set -a
# shellcheck disable=SC1090
. "$PLANE_DEV_ENV_FILE"
set +a

if [[ -z "${SECRET_KEY:-}" ]]; then
  printf 'error: SECRET_KEY is missing from %s\n' "$PLANE_DEV_ENV_FILE" >&2
  printf '       delete the file and let lib.sh regenerate it, then rebuild the template\n' >&2
  exit 1
fi

# Print a progress line. All output goes to stderr for commands whose stdout is
# consumed by callers (django-env.sh prints environment assignments).
note() {
  printf '==> %s\n' "$*" >&2
}

die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "required command not found: $1"
}

# docker compose pinned to the dev project and compose file. The top-level
# `name:` in compose.yml says the same; the explicit flag keeps the project
# independent of the caller's environment.
compose() {
  docker compose -f "$PLANE_COMPOSE_FILE" --project-name "$PLANE_COMPOSE_PROJECT" "$@"
}

# psql_dev <database> [psql arguments...]
#
# Prefers the host psql (14.x is fine against the 15 server) and falls back to
# the one inside the container. ON_ERROR_STOP is always on so failures abort
# the calling script.
psql_dev() {
  local db="$1"
  shift
  if command -v psql >/dev/null 2>&1; then
    PGPASSWORD="$PLANE_PG_PASSWORD" psql --no-psqlrc -X -q \
      -h "$PLANE_PG_HOST" -p "$PLANE_PG_PORT" -U "$PLANE_PG_USER" \
      -d "$db" -v ON_ERROR_STOP=1 "$@"
  else
    compose exec -T -e "PGPASSWORD=$PLANE_PG_PASSWORD" postgres \
      psql --no-psqlrc -X -q -U "$PLANE_PG_USER" -d "$db" -v ON_ERROR_STOP=1 "$@"
  fi
}

# service_health <compose service>
#
# Prints the Docker health status ("healthy", "starting", ...) or the container
# state when the service has no healthcheck. Prints "missing" when there is no
# container.
service_health() {
  local service="$1" cid
  cid="$(compose ps -q "$service" 2>/dev/null || true)"
  if [[ -z "$cid" ]]; then
    printf 'missing\n'
    return 0
  fi
  docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$cid"
}

# validate_db_name <name>
#
# Database names are interpolated into SQL identifiers, so restrict them to
# something that cannot escape a double-quoted identifier. Keeps to the
# `t_<task>_<n>` convention in apps/server/AGENTS.md and the 63-byte Postgres
# identifier limit.
validate_db_name() {
  local name="$1"
  [[ "$name" =~ ^[a-z][a-z0-9_]{0,62}$ ]] ||
    die "invalid database name '$name' (use lowercase letters, digits and underscores, max 63 chars, starting with a letter)"
}
