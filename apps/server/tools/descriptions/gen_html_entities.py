"""Generate `crates/plane-db/src/hooks/html_entities.rs`.

`strip_tags` feeds text through CPython's `HTMLParser(convert_charrefs=True)`,
which decodes character references with `html.unescape` (`Lib/html/__init__.py`).
That function is table-driven: the full HTML5 named-reference table
(`html.entities.html5`, 2231 keys including the semicolon-less legacy forms) and
two small tables of invalid references. The tables are embedded verbatim so the
port cannot drift from the interpreter that produced them.

Usage (from `apps/server/`):

    apps/api/.venv/bin/python tools/descriptions/gen_html_entities.py
    apps/api/.venv/bin/python tools/descriptions/gen_html_entities.py --check

The interpreter is pinned by `apps/api/.venv` (CPython 3.12.13). `--check`
fails when the committed file is stale, the way the other generators do.
"""

import html
import html.entities
import sys
from pathlib import Path

HEADER = """\
// Copyright (c) 2023-present Plane Software, Inc. and contributors
// SPDX-License-Identifier: AGPL-3.0-only
// See the LICENSE file for details.

//! Generated by `apps/server/tools/descriptions/gen_html_entities.py` from
//! CPython 3.12.13's `html` module. Do not edit by hand; re-run the generator.
//!
//! * [`NAMED`] is `html.entities.html5` verbatim (`sorted`, so a prefix search
//!   can walk it), including the semicolon-less legacy keys (`"amp"` next to
//!   `"amp;"`).
//! * [`INVALID_CHARREFS`] is `html._invalid_charrefs` (numeric references that
//!   map to another character, e.g. `&#13;` -> CR and the windows-1252 range).
//! * [`INVALID_CODEPOINTS`] is `html._invalid_codepoints` (references that
//!   `html.unescape` drops entirely).

"""


def rust_str(value: str) -> str:
    out = []
    for character in value:
        code = ord(character)
        if character == '"':
            out.append('\\"')
        elif character == "\\":
            out.append("\\\\")
        elif 0x20 <= code < 0x7F:
            out.append(character)
        else:
            out.append(f"\\u{{{code:x}}}")
    return "".join(out)


def render() -> str:
    named = sorted(html.entities.html5.items())
    lines = [HEADER, "/// `html.entities.html5`, sorted by key.\n"]
    lines.append("pub(super) static NAMED: &[(&str, &str)] = &[\n")
    for name, value in named:
        lines.append(f'    ("{rust_str(name)}", "{rust_str(value)}"),\n')
    lines.append("];\n\n")

    lines.append("/// `html._invalid_charrefs`: numeric reference -> replacement.\n")
    lines.append("pub(super) static INVALID_CHARREFS: &[(u32, &str)] = &[\n")
    for code, value in sorted(html._invalid_charrefs.items()):
        lines.append(f'    ({code}, "{rust_str(value)}"),\n')
    lines.append("];\n\n")

    lines.append("/// `html._invalid_codepoints`: numeric references `unescape` drops.\n")
    lines.append("pub(super) static INVALID_CODEPOINTS: &[u32] = &[\n")
    codes = sorted(html._invalid_codepoints)
    for index in range(0, len(codes), 12):
        chunk = ", ".join(str(code) for code in codes[index : index + 12])
        lines.append(f"    {chunk},\n")
    lines.append("];\n")
    return "".join(lines)


def main(argv: list[str]) -> int:
    target = (
        Path(__file__).resolve().parents[2]
        / "crates/plane-db/src/hooks/html_entities.rs"
    )
    rendered = render()
    if "--check" in argv:
        current = target.read_text() if target.exists() else ""
        if current != rendered:
            print(f"stale: {target}", file=sys.stderr)
            return 1
        print(f"ok: {target}")
        return 0
    target.write_text(rendered)
    print(f"wrote {target} ({len(rendered)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
