"""Record the drf-spectacular artefacts that Rust must serve byte for byte.

`RUST_REWRITE.md`'s Phase 7 exit condition is that the published API docs stay
accurate. The document is generated by drf-spectacular 0.29.0 from Django's own
URL resolver and serializers, so Django is the oracle: this script asks the real
`SpectacularAPIView`, `SpectacularSwaggerView` and `SpectacularRedocView` for
their responses and writes the bodies to `apps/server/deploy/openapi/`.

What is written
---------------
* `v1.yaml` -- `GET /api/schema/` (the view's default renderer).
* `v1.json` -- `GET /api/schema/?format=json`.
* `swagger-ui.html`, `redoc.html` -- the two HTML pages.
* `manifest.json` -- status and the ordered headers of each response, so the
  header contract is recorded next to the bodies. Django's test client keeps
  `Set-Cookie` out of `response.headers` (it exposes `response.cookies`), so the
  swagger page's `csrftoken` cookie is not recorded here; the differential
  scenario compares it on the wire (`volatile_cookies: csrftoken`).

The Rust port (`crates/plane-http-app/src/openapi/`) embeds these files and
serves them from the three routes when `ENABLE_DRF_SPECTACULAR=1`.

Determinism
-----------
The document depends only on the code (`plane/settings/openapi.py`,
`plane/utils/openapi/hooks.py` and the v1 serializers/views), never on the
database, Redis, the broker or the clock. Measured byte-identical between
`PYTHONHASHSEED=0` and `PYTHONHASHSEED=12345`. The two HTML pages contain no
request-dependent values for a bare `/api/schema/swagger-ui/` or
`/api/schema/redoc/` request: `schema_url` is the absolute path `/api/schema/`
(`drf_spectacular.plumbing.get_relative_url` strips only scheme and host).

The DRF anon throttle would need Redis for every request, and the captured
bodies do not depend on it, so the capture disables throttling in-process
(`override_settings(REST_FRAMEWORK=...)`). Nothing else about the settings is
changed; `ENABLE_DRF_SPECTACULAR` is forced to `1` before `django.setup()`
because the ambient environment may have it off.

Run it (from `apps/api`, as `apps/server/AGENTS.md` says):

    .venv/bin/python ../server/tools/openapi/capture.py           # write
    .venv/bin/python ../server/tools/openapi/capture.py --check   # verify

`--check` regenerates into memory and fails on any byte or header difference,
so an upstream view/serializer change, a drf-spectacular upgrade or a hand edit
of a committed artefact is caught. It is wired into `server-ci.yml`.
"""

from __future__ import annotations

import argparse
import json
import os
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve()
SERVER_ROOT = HERE.parents[2]  # apps/server
REPO_ROOT = HERE.parents[4]  # repository root
API_ROOT = REPO_ROOT / "apps" / "api"
OUT_DIR = SERVER_ROOT / "deploy" / "openapi"

# The schema itself is DB-independent; these values are deliberately dead so a
# missing environment cannot make the script reach a real service.
os.environ["ENABLE_DRF_SPECTACULAR"] = "1"
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "plane.settings.production")
os.environ.setdefault("SECRET_KEY", "openapi-capture-not-a-secret")
os.environ.setdefault("DATABASE_URL", "postgresql://x:x@127.0.0.1:1/x")
os.environ.setdefault("REDIS_URL", "redis://127.0.0.1:1/0")

sys.path.insert(0, str(API_ROOT))

import django  # noqa: E402

django.setup()

from django.test import Client  # noqa: E402
from django.test.utils import override_settings  # noqa: E402
from rest_framework.settings import api_settings  # noqa: E402

# `(file name, path, query)` in the order the views are documented.
CASES: list[tuple[str, str, dict[str, str]]] = [
    ("v1.yaml", "/api/schema/", {}),
    ("v1.json", "/api/schema/", {"format": "json"}),
    ("swagger-ui.html", "/api/schema/swagger-ui/", {}),
    ("redoc.html", "/api/schema/redoc/", {}),
]

# The Swagger UI page embeds `{{ csrf_token }}` from the template context: a
# **freshly masked** token, `mask + cipher`, where the mask is
# `get_random_string` on every call (`django/middleware/csrf.py:96-114`). Even
# Django cannot produce the same page twice, so the token is replaced by a
# placeholder in the committed artefact and by a real token at request time in
# the Rust handler.
CSRF_TOKEN_PLACEHOLDER = "__CSRF_TOKEN__"
_CSRF_TOKEN_RE = re.compile(r'(request\.headers\["X-CSRFTOKEN"\] = ")[A-Za-z0-9]{64}(")')


def mask_csrf_token(body: bytes) -> tuple[bytes, bool]:
    """Replace the swagger page's masked CSRF token with the placeholder.

    Returns the body and whether a replacement happened. The token is the only
    64-character alphanumeric string in the page; the regex pins the surrounding
    JS so a change in drf-spectacular's template is a stale-golden failure rather
    than a silent no-op.
    """
    text = body.decode("utf-8")
    masked, count = _CSRF_TOKEN_RE.subn(rf"\g<1>{CSRF_TOKEN_PLACEHOLDER}\g<2>", text)
    if count not in (0, 1):
        raise SystemExit(f"expected at most one CSRF token in the page, found {count}")
    return masked.encode("utf-8"), bool(count)


def render() -> tuple[dict[str, bytes], dict]:
    """Ask Django for all four responses; return `(bodies, manifest)`."""
    # The anon throttle needs Redis and cannot change the body. Everything else
    # (renderers, permissions, middleware) stays as production configures it.
    rest_framework = dict(api_settings.user_settings)
    rest_framework["DEFAULT_THROTTLE_CLASSES"] = ()
    bodies: dict[str, bytes] = {}
    manifest: dict = {"cases": [], "masked": []}
    with override_settings(REST_FRAMEWORK=rest_framework):
        client = Client()
        for name, path, query in CASES:
            response = client.get(path, query)
            if response.status_code != 200:
                raise SystemExit(
                    f"{path} {query} answered {response.status_code}, expected 200; "
                    "the capture would record an error page"
                )
            body = response.content
            if name == "swagger-ui.html":
                body, masked = mask_csrf_token(body)
                if not masked:
                    raise SystemExit(
                        "the Swagger UI page no longer embeds a CSRF token; "
                        "the masked golden would serve a stale page"
                    )
                manifest["masked"].append(
                    {
                        "file": name,
                        "field": "csrf_token",
                        "placeholder": CSRF_TOKEN_PLACEHOLDER,
                        "why": "get_token() masks a fresh random mask on every call "
                        "(django/middleware/csrf.py:96-114); the Rust handler substitutes "
                        "the request's own token",
                    }
                )
            bodies[name] = body
            manifest["cases"].append(
                {
                    "file": name,
                    "request": {"path": path, "query": query},
                    "status": response.status_code,
                    "headers": [[key, value] for key, value in response.headers.items()],
                }
            )
    return bodies, manifest


def manifest_bytes(manifest: dict) -> bytes:
    return (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode()


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed artefacts instead of writing them",
    )
    args = parser.parse_args(argv)

    bodies, manifest = render()
    bodies["manifest.json"] = manifest_bytes(manifest)

    failures = 0
    for name, body in bodies.items():
        path = OUT_DIR / name
        if args.check:
            existing = path.read_bytes() if path.exists() else None
            if existing != body:
                failures += 1
                print(
                    f"STALE {path.relative_to(REPO_ROOT)}: "
                    f"committed {len(existing) if existing is not None else 0} bytes, "
                    f"Django now produces {len(body)} bytes",
                    file=sys.stderr,
                )
            else:
                print(f"ok    {path.relative_to(REPO_ROOT)} ({len(body)} bytes)")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(body)
            print(f"wrote {path.relative_to(REPO_ROOT)} ({len(body)} bytes)")

    if failures:
        print(
            "The OpenAPI artefacts are stale. Regenerate them with "
            "`apps/api/.venv/bin/python apps/server/tools/openapi/capture.py` "
            "and review the diff: it is the published v1 API contract.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
