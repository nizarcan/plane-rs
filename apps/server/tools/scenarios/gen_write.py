"""Generate a starter write scenario for a set of routes.

A domain agent's first hour on a write group should not be spent inventing
YAML. This reads `routes.json` (the route inventory) and
`scenarios/fixtures/fix_tpl.json` (the fixture manifest), asks Django for the
serializer each write action uses, and emits one step per method: a plausible
body built from the serializer's *writable* fields, a capture of the created
row's id from the step's database diff, and an obvious denial case from a
non-member session.

The result is a starting point, not a finished scenario: bodies need review
(``description``/``html`` pairs, choice values, required relations), and every
step needs an expected status once it has run. The example in
``scenarios/write/stickies-harness.yaml`` shows what the finished shape looks
like.

Usage (from ``apps/server``)::

    # every unsafe method of routes 223 and 224
    ../api/.venv/bin/python tools/scenarios/gen_write.py --orders 223,224

    # one route group, written to a file
    ../api/.venv/bin/python tools/scenarios/gen_write.py --group stickies \\
        --out scenarios/write/stickies.yaml

    # print instead of writing, and see the serializer fields it skipped
    ../api/.venv/bin/python tools/scenarios/gen_write.py --orders 223 --stdout -v

The script needs the dev environment only to import the Django settings module
(it runs no query): missing variables are filled from the same defaults as
``dev/lib.sh``.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

SERVER_DIR = Path(__file__).resolve().parents[2]
REPO_ROOT = SERVER_DIR.parents[1]
ROUTES_JSON = SERVER_DIR / "routes.json"
FIXTURE_MANIFEST = SERVER_DIR / "scenarios" / "fixtures" / "fix_tpl.json"

HEADER = """\
# Copyright (c) 2023-present Plane Software, Inc. and contributors
# SPDX-License-Identifier: AGPL-3.0-only
# See the LICENSE file for details.
#
# GENERATED by apps/server/tools/scenarios/gen_write.py. Review every body and
# expected status before trusting it; the generator only knows the serializer's
# writable fields, not the view's rules.
"""

# Fields every write body leaves to the server.
SKIP_FIELDS = {
    "id",
    "created_at",
    "updated_at",
    "deleted_at",
    "created_by",
    "updated_by",
    "workspace",
    "workspace_id",
    "sort_order",
}

# A fixture variable per related model, from `scenarios/fixtures/fix_tpl.json`.
RELATED = {
    "Project": "project_alpha",
    "State": "state_alpha_todo",
    "Label": "label_alpha_bug",
    "Cycle": "cycle_alpha_current",
    "Module": "module_alpha_in_progress",
    "Issue": "issue_alpha",
    "EstimatePoint": "estimate_point_alpha_points_3",
    "User": "user_member_id",
    "Sticky": "sticky_0",
}

UNSAFE = ("post", "put", "patch", "delete")

URL_PARAMS = {
    "slug": "ws",
    "project_id": "project_alpha",
    "workspace_slug": "ws",
}


