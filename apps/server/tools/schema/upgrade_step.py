"""Turn Django migrations into a `plane-migrator` upgrade step.

Run against the *target* oracle while moving the pin (`UPGRADING.md`):

    PLANE_RS_UPSTREAM_COMMIT=<new sha> \\
    PLANE_RS_ORACLE_DIR=$HOME/.cache/plane-rs/oracle/<new sha> \\
      apps/server/tools/upstream/oracle.sh fetch
    PLANE_RS_UPSTREAM_COMMIT=<new sha> \\
    PLANE_RS_ORACLE_DIR=$HOME/.cache/plane-rs/oracle/<new sha> \\
      "$(apps/server/tools/upstream/oracle.sh python)" \\
      apps/server/tools/schema/upgrade_step.py \\
        --step 0001 --app db --migration 0126_add_widget \\
        --from 'db:0125_reset_project_deploy_board_identity,license:0006_instance_is_current_version_deprecated' \\
        --to   'db:0126_add_widget,license:0006_instance_is_current_version_deprecated'

It writes `apps/server/deploy/schema/upgrade_steps/0001_db_0126_add_widget.sql`
(the statements `manage.py sqlmigrate` prints, without its `BEGIN`/`COMMIT`)
and prints the `UpgradeStep` entry to paste into
`bins/plane-migrator/src/upgrade.rs`, oldest first.

`sqlmigrate` prints nothing for a `RunPython` migration. The script says so
explicitly: write the backfill by hand, review it against the Python body, and
use the same `migrations` rows. Never add a step that only records history.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve()
SERVER_DIR = HERE.parents[2]  # apps/server
REPO_ROOT = HERE.parents[4]

sys.path.insert(0, str(SERVER_DIR / "tools" / "upstream"))
import oracle  # noqa: E402

OUT_DIR = SERVER_DIR / "deploy" / "schema" / "upgrade_steps"
HEADER = """\
-- Copyright (c) 2023-present Plane Software, Inc. and contributors
-- SPDX-License-Identifier: AGPL-3.0-only
-- See the LICENSE file for details.
--
-- @generated by tools/schema/upgrade_step.py from `manage.py sqlmigrate {app} {migration}`
-- at upstream {commit}. Do not edit by hand unless the script says the
-- migration is a RunPython step; then this file is the reviewed backfill.
--
"""


def sqlmigrate(app: str, migration: str) -> str:
    env = dict(os.environ)
    env.setdefault("DJANGO_SETTINGS_MODULE", "plane.settings.production")
    env.setdefault("SECRET_KEY", "upgrade-step-generator")
    env.setdefault("DATABASE_URL", "postgresql://x:x@127.0.0.1:1/x")
    env.setdefault("REDIS_URL", "redis://127.0.0.1:1/0")
    env.setdefault("ENABLE_READ_REPLICA", "0")
    env.setdefault("PYTHONDONTWRITEBYTECODE", "1")
    result = subprocess.run(
        [sys.executable, "manage.py", "sqlmigrate", app, migration],
        cwd=oracle.api_dir(),
        env=env,
        text=True,
        capture_output=True,
        check=False,
    )
    if result.returncode != 0:
        raise SystemExit(
            f"manage.py sqlmigrate {app} {migration} failed:\n{result.stderr}"
        )
    return result.stdout


def strip_transaction(sql: str) -> str:
    """Drop sqlmigrate's wrapper; the migrator runs each step in a transaction."""
    lines = [line for line in sql.splitlines() if line.strip().upper() not in ("BEGIN;", "COMMIT;")]
    return "\n".join(lines).strip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--step", required=True, help="four-digit step id, e.g. 0001")
    parser.add_argument("--app", required=True)
    parser.add_argument("--migration", required=True)
    parser.add_argument("--from", dest="from_id", required=True, help="baseline id the step applies to")
    parser.add_argument("--to", dest="to_id", required=True, help="baseline id after the step")
    parser.add_argument(
        "--extra-migration",
        action="append",
        default=[],
        metavar="APP.NAME",
        help="another migration row the step records (repeatable)",
    )
    parser.add_argument("--out-dir", type=Path, default=OUT_DIR)
    parser.add_argument("--stdout", action="store_true", help="print the SQL instead of writing")
    args = parser.parse_args(argv)

    sql = strip_transaction(sqlmigrate(args.app, args.migration))
    if not re.search(r"\S", sql):
        print(
            f"warning: {args.app}.{args.migration} produces no SQL "
            "(a RunPython/state-only migration). Write the backfill by hand and "
            "review it; see the module docstring.",
            file=sys.stderr,
        )
    commit = oracle.upstream_commit()
    body = HEADER.format(app=args.app, migration=args.migration, commit=commit) + sql
    if args.stdout:
        print(body)
    else:
        args.out_dir.mkdir(parents=True, exist_ok=True)
        name = f"{args.step}_{args.app}_{args.migration}.sql"
        path = args.out_dir / name
        path.write_text(body, encoding="utf-8")
        print(f"wrote {path}")

    rows = [(args.app, args.migration)]
    for extra in args.extra_migration:
        app, _, migration = extra.partition(".")
        if not app or not migration:
            raise SystemExit(f"--extra-migration expects APP.NAME, got {extra!r}")
        rows.append((app, migration))
    rendered_rows = ", ".join(f'("{app}", "{migration}")' for app, migration in rows)
    rel = f"deploy/schema/upgrade_steps/{args.step}_{args.app}_{args.migration}.sql"
    print()
    print("Add to bins/plane-migrator/src/upgrade.rs (oldest first), then regenerate")
    print("deploy/schema/baseline.sql at the new pin (tools/schema/baseline.py --write):")
    print()
    print("    UpgradeStep {")
    print(f'        id: "{args.step}",')
    print(f'        from: "{args.from_id}",')
    print(f'        to: "{args.to_id}",')
    print(f'        sql: include_str!("../../../{rel}"),')
    print(f"        migrations: &[{rendered_rows}],")
    print("    },")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
