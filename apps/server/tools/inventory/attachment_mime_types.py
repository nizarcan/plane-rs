"""Generate the Rust copy of ``settings.ATTACHMENT_MIME_TYPES``.

Django is the specification (``RUST_REWRITE.md``): the app attachment upload
route compares the client's ``type`` against
``settings.ATTACHMENT_MIME_TYPES``
(``plane/app/views/issue/attachment.py:133``, ``plane/api/views/issue.py:2069``,
``plane/api/views/asset.py:538``). The setting is a hand-maintained list in
``plane/settings/common.py:505-593``; Rust used to carry a hand-copied subset,
which silently rejected almost half of the types Django accepts.

This script imports the setting from the real Django (the already-synced
virtualenv; no database, Redis or broker is contacted) and writes one constant:

    apps/server/crates/plane-http-app/src/generated/attachment_mime_types.rs

Membership is what the view checks, so the generated list is sorted and
de-duplicated (Django's list repeats ``text/markdown``); the doc comment records
the original count.

Usage::

    cd apps/api && .venv/bin/python ../server/tools/inventory/attachment_mime_types.py
    cd apps/api && .venv/bin/python ../server/tools/inventory/attachment_mime_types.py --check

``--check`` regenerates in memory and exits 1 when the committed file differs,
so a hand edit or a Django change without a regeneration fails in CI.
"""

from __future__ import annotations

import argparse
import os
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve()
SERVER_ROOT = HERE.parents[2]  # apps/server
API_ROOT = HERE.parents[3] / "api"  # apps/api
OUT_PATH = SERVER_ROOT / "crates/plane-http-app/src/generated/attachment_mime_types.rs"
SETTING_SOURCE = "plane/settings/common.py:505-593"

# Throwaway values so importing the settings cannot reach a real service. The
# setting is a constant list; nothing below opens a connection.
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "plane.settings.production")
os.environ.setdefault("SECRET_KEY", "attachment-mime-types-not-a-secret")
os.environ.setdefault("DATABASE_URL", "postgresql://x:x@127.0.0.1:1/x")
os.environ.setdefault("REDIS_URL", "redis://127.0.0.1:1/0")

if str(API_ROOT) not in sys.path:
    sys.path.insert(0, str(API_ROOT))


def django_mime_types() -> list[str]:
    import django

    django.setup()
    from django.conf import settings

    return list(settings.ATTACHMENT_MIME_TYPES)


def render(mime_types: list[str]) -> str:
    unique = sorted(set(mime_types))
    lines = [
        "// Copyright (c) 2023-present Plane Software, Inc. and contributors",
        "// SPDX-License-Identifier: AGPL-3.0-only",
        "// See the LICENSE file for details.",
        "//",
        "// @generated by tools/inventory/attachment_mime_types.py -- do not edit by hand.",
        "// Regenerate with:",
        "//   cd apps/api && .venv/bin/python \\",
        "//       ../server/tools/inventory/attachment_mime_types.py",
        "",
        f"//! `settings.ATTACHMENT_MIME_TYPES` (`{SETTING_SOURCE}`).",
        "//!",
        f"//! Django's list has {len(mime_types)} entries ({len(unique)} unique; `text/markdown`",
        "//! appears twice), and the upload views test membership, not order.",
        "",
        "/// Every MIME type the app attachment upload route accepts.",
        "///",
        "/// `plane/app/views/issue/attachment.py:133`:",
        "/// `if not type or type not in settings.ATTACHMENT_MIME_TYPES`.",
        f"pub const ATTACHMENT_MIME_TYPES: [&str; {len(unique)}] = [",
    ]
    lines.extend(f'    "{mime_type}",' for mime_type in unique)
    lines.extend(["];", ""])
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the generated Rust constant is stale",
    )
    arguments = parser.parse_args(argv)

    mime_types = django_mime_types()
    content = render(mime_types)
    if arguments.check:
        if not OUT_PATH.exists():
            print(f"missing generated file: {OUT_PATH}", file=sys.stderr)
            return 1
        if OUT_PATH.read_text(encoding="utf-8") != content:
            print(
                f"stale generated file: {OUT_PATH}\n"
                "regenerate with tools/inventory/attachment_mime_types.py",
                file=sys.stderr,
            )
            return 1
        print(
            f"attachment mime types: ok ({len(set(mime_types))} unique of "
            f"{len(mime_types)} Django entries)"
        )
        return 0

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(content, encoding="utf-8")
    print(
        f"wrote {OUT_PATH} ({len(set(mime_types))} unique of "
        f"{len(mime_types)} Django entries)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
