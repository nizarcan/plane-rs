//! The normalisation table and its implementation.
//!
//! Only legitimately nondeterministic values are rewritten, and every rewrite
//! is either a rule from `scenarios/normalize.yaml` (which must carry a
//! one-line justification) or one of the four built-in rules below. The
//! rewrite is per target, so target A's generated UUID is mapped to the same
//! placeholder as target B's independently generated one.
//!
//! **Consistent placeholders.** Every volatile value becomes a typed
//! placeholder from one per-target map: `<session:1>`, `<csrf-secret:1>`,
//! `<csrf-token:1>`, `<username:1>`, `<token:1>`, `<colour:1>`, `<id:1>`.
//! The same raw value anywhere in the run — a `Set-Cookie` value, a JSON body
//! field, a database column, a Redis key or value, a Celery argument — becomes
//! the same placeholder, so cross-references are checked rather than erased.
//!
//! **Shapes first.** Every placeholder rule names a shape in `normalize.yaml`;
//! the value is matched against it on both targets *before* substitution, so a
//! session key of the wrong length or a non-hex username is a difference.
//!
//! **Semantics.** Session payloads are verified and decoded with the target's
//! `SECRET_KEY`, CSRF tokens must unmask to the cookie of the same response,
//! and password hashes are re-derived from the declared plaintext.
//!
//! Order of placeholder assignment, fixed by the design:
//! 1. response headers, `Location` first, then the other headers by name;
//! 2. response body in document order (objects preserve wire key order);
//! 3. database diff, by table name and then by row content with volatile
//!    parts masked;
//! 4. Celery messages, by queue name and delivery order;
//! 5. Redis diff, by masked key name.
//!
//! The mapping persists for the whole run, so `<session:3>` always means "the
//! third session key generated by this target".

