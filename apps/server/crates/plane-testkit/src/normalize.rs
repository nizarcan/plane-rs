//! The normalisation table and its implementation.
//!
//! Only legitimately nondeterministic values are rewritten, and every rewrite
//! is either a rule from `scenarios/normalize.yaml` (which must carry a
//! one-line justification) or one of the four built-in rules below. The
//! rewrite is per target, so target A's generated UUID is mapped to the same
//! placeholder as target B's independently generated one.
//!
//! Order of placeholder assignment, fixed by the design:
//! 1. response headers, `Location` first, then the other headers by name;
//! 2. response body in document order (objects preserve wire key order);
//! 3. database diff, by table name and then by row content with volatile
//!    parts masked;
//! 4. Celery messages, by queue name and delivery order.
//!
//! The mapping persists for the whole run, so `<id:3>` always means "the
//! third id generated by this target".

use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::sync::Arc;

use chrono::{DateTime, Duration, Utc};
use serde::Serialize;
use serde_json::{Value, json};

use crate::celery::CeleryMessage;
use crate::config::{NormalizeRules, ValueMode};
use crate::cookies::{ParsedCookie, canonical_set_cookie, parse_set_cookie};
use crate::db::DbDiff;
use crate::timeparse::{is_uuid, parse_http_date, parse_timestamp, timestamp_regex, uuid_regex};

pub const UUID_WHY: &str =
    "UUID generated during the run and not present in the baseline database snapshot";
pub const TIMESTAMP_WHY: &str = "ISO-8601 timestamp that falls inside the target's own step window";
pub const BASE_URL_WHY: &str =
    "the target's own base URL; each target listens on a different local port";
pub const COOKIE_EXPIRES_WHY: &str =
    "cookie Expires is relative to the step clock (Django writes now + cookie age)";
pub const KOMBU_UUID_WHY: &str =
    "Celery's kombu JSON encoder wraps UUID objects as {__type__: uuid, __value__: {hex}}";
pub const KOMBU_DATETIME_WHY: &str =
    "Celery's kombu JSON encoder wraps datetime objects as {__type__: datetime, __value__: iso}";
pub const GZIP_RANDOM_WHY: &str = "Django's gzip adds a random 1-100 byte filename (BREACH mitigation), so a body near the 200-byte threshold may or may not be compressed";

#[derive(Debug, Clone, PartialEq)]
pub enum BodyValue {
    Json(Value),
    Text(String),
    Binary(String),
}

#[derive(Debug, Clone, PartialEq)]
pub struct NormalizedBody {
    pub value: BodyValue,
    pub modified: bool,
}

impl NormalizedBody {
    pub fn pretty(&self) -> String {
        match &self.value {
            BodyValue::Json(value) => {
                serde_json::to_string_pretty(value).unwrap_or_else(|_| "<invalid json>".to_string())
            }
            BodyValue::Text(text) => text.clone(),
            BodyValue::Binary(hex) => format!("<binary {hex}>"),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct AppliedRule {
    pub rule: String,
    pub why: String,
}

pub struct TargetNormalizer {
    rules: Arc<NormalizeRules>,
    base_url: String,
    known_uuids: Arc<HashSet<String>>,
    uuid_map: HashMap<String, String>,
    next_uuid: usize,
    /// Timestamps this target wrote in an earlier step. A later step can
    /// update a row written earlier, so the "before" value in its diff is a
    /// timestamp from outside the current window; it is the same in-run
    /// value, so it stays `<now>`.
    remembered_timestamps: HashSet<String>,
    window: Option<(DateTime<Utc>, DateTime<Utc>)>,
    applied: BTreeMap<String, String>,
    volatile_cookies: HashMap<String, (ValueMode, String)>,
    volatile_json_keys: HashMap<String, (ValueMode, String)>,
    volatile_celery_headers: BTreeSet<String>,
    db_columns: HashMap<String, (ValueMode, String)>,
}

impl TargetNormalizer {
    pub fn new(
        rules: Arc<NormalizeRules>,
        base_url: impl Into<String>,
        known_uuids: Arc<HashSet<String>>,
    ) -> Self {
        let volatile_cookies = rules
            .volatile_cookies
            .iter()
            .map(|rule| (rule.name.clone(), (rule.mode, rule.why.clone())))
            .collect();
        let volatile_json_keys = rules
            .volatile_json_keys
            .iter()
            .map(|rule| (rule.name.clone(), (rule.mode, rule.why.clone())))
            .collect();
        let volatile_celery_headers = rules
            .volatile_celery_headers
            .iter()
            .map(|rule| rule.name.to_ascii_lowercase())
            .collect();
        let db_columns = rules
            .volatile_db_columns
            .iter()
            .map(|rule| {
                (
                    format!("{}.{}", rule.table, rule.column),
                    (rule.mode, rule.why.clone()),
                )
            })
            .collect();
        Self {
            rules,
            base_url: base_url.into(),
            known_uuids,
            uuid_map: HashMap::new(),
            next_uuid: 1,
            remembered_timestamps: HashSet::new(),
            window: None,
            applied: BTreeMap::new(),
            volatile_cookies,
            volatile_json_keys,
            volatile_celery_headers,
            db_columns,
        }
    }

    /// Open the step's timestamp window: request start − slack to response end
    /// + slack. Times outside it are compared exactly.
    pub fn start_step(&mut self, started: DateTime<Utc>, ended: DateTime<Utc>) {
        let slack = Duration::seconds(self.rules.timestamp_slack_secs);
        self.window = Some((started - slack, ended + slack));
    }

    /// Record an externally-applied rule (the runner normalises the
    /// content-encoding header because Django's gzip output is randomised).
    pub fn note_rule(&mut self, rule: &str, why: &str) {
        self.record(rule, why);
    }

    pub fn applied(&self) -> Vec<AppliedRule> {
        self.applied
            .iter()
            .map(|(rule, why)| AppliedRule {
                rule: rule.clone(),
                why: why.clone(),
            })
            .collect()
    }

    pub fn placeholder_count(&self) -> usize {
        self.next_uuid - 1
    }

    pub fn rules(&self) -> &NormalizeRules {
        &self.rules
    }

    // -- strings ----------------------------------------------------------

    /// Rewrite a single string, replacing this target's base URL, generated
    /// UUIDs and in-window timestamps.
    pub fn normalize_text(&mut self, text: &str) -> String {
        let mut result = self.replace_base_url(text);
        if result != text {
            self.record("target-base-url", BASE_URL_WHY);
        }
        if uuid_regex().is_match(&result) {
            let known = Arc::clone(&self.known_uuids);
            result = uuid_regex()
                .replace_all(&result, |captures: &regex::Captures<'_>| {
                    let matched = captures
                        .get(0)
                        .map(|m| m.as_str())
                        .unwrap_or_default()
                        .to_string();
                    if known.contains(&matched) {
                        matched
                    } else {
                        self.placeholder_for(&matched)
                    }
                })
                .into_owned();
        }
        if timestamp_regex().is_match(&result) {
            let mut replaced = false;
            result = timestamp_regex()
                .replace_all(&result, |captures: &regex::Captures<'_>| {
                    let matched = captures.get(0).map(|m| m.as_str()).unwrap_or_default();
                    if self.remembered_timestamps.contains(matched) {
                        replaced = true;
                        return "<now>".to_string();
                    }
                    match parse_timestamp(matched) {
                        Some(at) if self.in_window(at) => {
                            self.remembered_timestamps.insert(matched.to_string());
                            replaced = true;
                            "<now>".to_string()
                        }
                        _ => matched.to_string(),
                    }
                })
                .into_owned();
            if replaced {
                self.record("timestamp-window", TIMESTAMP_WHY);
            }
        }
        result
    }

    fn replace_base_url(&self, text: &str) -> String {
        if self.base_url.is_empty() || !text.contains(&self.base_url) {
            return text.to_string();
        }
        text.replace(&self.base_url, "<base>")
    }

    fn placeholder_for(&mut self, uuid: &str) -> String {
        if let Some(existing) = self.uuid_map.get(uuid) {
            return existing.clone();
        }
        let placeholder = format!("<id:{}>", self.next_uuid);
        self.next_uuid += 1;
        self.uuid_map.insert(uuid.to_string(), placeholder.clone());
        self.record("uuid-placeholder", UUID_WHY);
        placeholder
    }

    fn in_window(&self, at: DateTime<Utc>) -> bool {
        self.window
            .is_some_and(|(start, end)| at >= start && at <= end)
    }

    // -- headers ----------------------------------------------------------

    /// Normalise response headers. `Location` is processed first so id
    /// placeholders follow the order the design fixes.
    pub fn normalize_headers(&mut self, headers: &[(String, String)]) -> Vec<(String, String)> {
        let mut order: Vec<usize> = (0..headers.len()).collect();
        order.sort_by_cached_key(|&index| {
            let name = headers[index].0.to_ascii_lowercase();
            let rank = u8::from(name != "location");
            (rank, name, index)
        });
        let mut out = headers.to_vec();
        for index in order {
            let (name, value) = &headers[index];
            out[index].1 = if name.eq_ignore_ascii_case("set-cookie") {
                self.normalize_set_cookie(value)
            } else {
                self.normalize_text(value)
            };
        }
        out
    }

    fn normalize_set_cookie(&mut self, raw: &str) -> String {
        let Some(cookie) = parse_set_cookie(raw) else {
            return self.normalize_text(raw);
        };
        let mut value = cookie.value.clone();
        if let Some((mode, why)) = self.volatile_cookies.get(&cookie.name).cloned() {
            value = apply_string_mode(mode, &value);
            if value != cookie.value {
                self.record(&format!("cookie:{}", cookie.name), &why);
            }
        } else {
            value = self.normalize_text(&value);
        }
        let mut attributes = cookie.attributes.clone();
        for (key, attribute_value) in &mut attributes {
            if key.eq_ignore_ascii_case("expires") {
                if let Some(relative) = self.relative_expiry(attribute_value) {
                    *attribute_value = relative;
                    self.record("cookie:expires", COOKIE_EXPIRES_WHY);
                }
            } else {
                *attribute_value = self.normalize_text(attribute_value);
            }
        }
        canonical_set_cookie(
            &ParsedCookie {
                name: cookie.name,
                value: value.clone(),
                attributes,
            },
            &value,
        )
    }

    /// Cookie `Expires` is `now + age`, so compare the age rounded to 10 s
    /// instead of the wall-clock value.
    fn relative_expiry(&self, value: &str) -> Option<String> {
        let expires = parse_http_date(value)?;
        let (start, _) = self.window?;
        if expires < start - Duration::hours(1) || expires > start + Duration::days(400) {
            return None;
        }
        let seconds = (expires - start).num_seconds();
        let rounded = ((seconds + 5) / 10) * 10;
        Some(format!("<expires+{rounded}s>"))
    }

    /// A database timestamp that is a fixed offset from the step clock (for
    /// example `sessions.expire_date = now + SESSION_COOKIE_AGE`). Compare the
    /// rounded offset, not the wall-clock value.
    fn relative_timestamp(&self, value: &str) -> Option<String> {
        let at = parse_timestamp(value)?;
        let (start, _) = self.window?;
        let seconds = (at - start).num_seconds();
        if !(-400 * 86_400..=400 * 86_400).contains(&seconds) {
            return None;
        }
        let rounded = ((seconds + 5) / 10) * 10;
        Some(format!("<offset{rounded:+}s>"))
    }

    // -- bodies -----------------------------------------------------------

    pub fn normalize_body(&mut self, raw: &[u8], json_content_type: bool) -> NormalizedBody {
        if raw.is_empty() {
            return NormalizedBody {
                value: BodyValue::Text(String::new()),
                modified: false,
            };
        }
        if json_content_type && let Ok(mut value) = serde_json::from_slice::<Value>(raw) {
            let before = value.clone();
            self.normalize_json(&mut value);
            return NormalizedBody {
                value: BodyValue::Json(value.clone()),
                modified: value != before,
            };
        }
        match std::str::from_utf8(raw) {
            Ok(text) => {
                let normalised = self.normalize_text(text);
                NormalizedBody {
                    modified: normalised != text,
                    value: BodyValue::Text(normalised),
                }
            }
            Err(_) => NormalizedBody {
                value: BodyValue::Binary(hex_encode(raw)),
                modified: false,
            },
        }
    }

    fn normalize_json(&mut self, value: &mut Value) {
        match value {
            Value::Object(map) => {
                if self.normalize_kombu_envelope(map) {
                    return;
                }
                let keys: Vec<String> = map.keys().cloned().collect();
                for key in keys {
                    let Some(slot) = map.get_mut(&key) else {
                        continue;
                    };
                    match self.volatile_json_keys.get(&key).cloned() {
                        Some((mode, why)) => {
                            let before = slot.clone();
                            if mode == ValueMode::UnixTime {
                                self.normalize_unix_time(slot);
                            } else {
                                apply_json_mode(mode, slot);
                            }
                            if *slot != before {
                                self.record(&format!("json:{key}"), &why);
                            }
                        }
                        None => self.normalize_json(slot),
                    }
                }
            }
            Value::Array(items) => {
                for item in items {
                    self.normalize_json(item);
                }
            }
            Value::String(text) => {
                *text = self.normalize_text(text);
            }
            _ => {}
        }
    }

    /// A whole-second Unix timestamp produced by `int(timezone.now()
    /// .timestamp())`. Replace it with `<epoch>` when it is close to the step
    /// clock; values from an earlier period stay exact.
    fn normalize_unix_time(&self, value: &mut Value) {
        let seconds = match value {
            Value::Number(number) => number
                .as_i64()
                .or_else(|| number.as_f64().map(|seconds| seconds as i64)),
            Value::String(text) => text.parse::<i64>().ok(),
            _ => None,
        };
        let Some(seconds) = seconds else {
            return;
        };
        let Some((start, _)) = self.window else {
            return;
        };
        let delta = seconds.saturating_sub(start.timestamp()).unsigned_abs();
        if delta <= 400 * 86_400 {
            *value = json!("<epoch>");
        }
    }

    /// Celery's kombu JSON encoder wraps non-JSON Python types in
    /// `{"__type__": ..., "__value__": ...}`: UUIDs become
    /// `{"__type__":"uuid","__value__":{"hex":"..."}}` and datetimes keep an
    /// ISO-8601 string. Unwrap those two; everything else is normal.
    fn normalize_kombu_envelope(&mut self, map: &mut serde_json::Map<String, Value>) -> bool {
        if map.len() != 2 {
            return false;
        }
        let Some(kind) = map
            .get("__type__")
            .and_then(Value::as_str)
            .map(str::to_string)
        else {
            return false;
        };
        let Some(inner) = map.get_mut("__value__") else {
            return false;
        };
        match kind.as_str() {
            "uuid" => {
                let Some(hex) = inner.get("hex").and_then(Value::as_str).map(str::to_string) else {
                    return false;
                };
                let Some(dashed) = dash_uuid(&hex) else {
                    return false;
                };
                let placeholder = self.placeholder_for(&dashed);
                *inner = json!({ "hex": placeholder });
                self.record("celery-kombu-uuid", KOMBU_UUID_WHY);
                true
            }
            "datetime" | "date" => {
                let Some(text) = inner.as_str().map(str::to_string) else {
                    return false;
                };
                let normalised = self.normalize_text(&text);
                if normalised == text {
                    return false;
                }
                *inner = Value::String(normalised);
                self.record("celery-kombu-datetime", KOMBU_DATETIME_WHY);
                true
            }
            _ => false,
        }
    }

    // -- database ---------------------------------------------------------

    pub fn normalize_db_diff(&mut self, diff: &mut DbDiff) {
        for (table, table_diff) in &mut diff.tables {
            // The design fixes the id order as "row content with UUIDs
            // masked"; sorting uses that masked content.
            self.sort_rows(&mut table_diff.inserted);
            self.sort_rows(&mut table_diff.deleted);
            self.sort_rows(&mut table_diff.updated);

            for row in &mut table_diff.inserted {
                self.normalize_db_row(table, row);
            }
            for row in &mut table_diff.deleted {
                self.normalize_db_row(table, row);
            }
            for update in &mut table_diff.updated {
                let Value::Object(map) = update else { continue };
                if let Some(pk) = map.get_mut("pk") {
                    self.normalize_json(pk);
                }
                if let Some(changed) = map.get_mut("changed") {
                    let columns: Vec<String> = changed
                        .as_object()
                        .map(|changed| changed.keys().cloned().collect())
                        .unwrap_or_default();
                    for column in columns {
                        let Some(entry) = changed.get_mut(&column) else {
                            continue;
                        };
                        let Value::Object(entry) = entry else {
                            continue;
                        };
                        for side in ["a", "b"] {
                            if let Some(value) = entry.get_mut(side) {
                                self.normalize_db_value(table, &column, value);
                            }
                        }
                    }
                }
            }
        }
    }

    fn sort_rows(&self, rows: &mut [Value]) {
        rows.sort_by_cached_key(|row| match serde_json::to_string(row) {
            Ok(text) => self.mask_for_sort(&text),
            Err(_) => String::new(),
        });
    }

    fn mask_for_sort(&self, text: &str) -> String {
        let masked = uuid_regex()
            .replace_all(text, "00000000-0000-0000-0000-000000000000")
            .into_owned();
        timestamp_regex()
            .replace_all(&masked, |captures: &regex::Captures<'_>| {
                let matched = captures.get(0).map(|m| m.as_str()).unwrap_or_default();
                match parse_timestamp(matched) {
                    Some(at) if self.in_window(at) => "<now>".to_string(),
                    _ => matched.to_string(),
                }
            })
            .into_owned()
    }

    fn normalize_db_row(&mut self, table: &str, row: &mut Value) {
        let Value::Object(map) = row else {
            self.normalize_json(row);
            return;
        };
        let columns: Vec<String> = map.keys().cloned().collect();
        for column in columns {
            let Some(value) = map.get_mut(&column) else {
                continue;
            };
            self.normalize_db_value(table, &column, value);
        }
    }

    fn normalize_db_value(&mut self, table: &str, column: &str, value: &mut Value) {
        let bare_table = table.rsplit('.').next().unwrap_or(table);
        if let Some((mode, why)) = self
            .db_columns
            .get(&format!("{bare_table}.{column}"))
            .cloned()
        {
            let before = value.clone();
            if mode == ValueMode::RelativeTime {
                if let Value::String(text) = value
                    && let Some(relative) = self.relative_timestamp(text)
                {
                    *value = Value::String(relative);
                }
            } else {
                apply_json_mode(mode, value);
            }
            if *value != before {
                self.record(&format!("db:{bare_table}.{column}"), &why);
            }
            return;
        }
        self.normalize_json(value);
    }

    // -- celery -----------------------------------------------------------

    pub fn normalize_celery(&mut self, message: &mut CeleryMessage) {
        message.headers.retain(|key, _| {
            !self
                .volatile_celery_headers
                .contains(&key.to_ascii_lowercase())
        });
        let headers: Vec<String> = message.headers.keys().cloned().collect();
        for key in headers {
            let Some(value) = message.headers.get_mut(&key) else {
                continue;
            };
            if key == "argsrepr" || key == "kwargsrepr" {
                if let Some(text) = value.as_str() {
                    *value = Value::String(self.normalize_text(text));
                }
            } else {
                self.normalize_json(value);
            }
        }
        self.normalize_json(&mut message.args);
        self.normalize_json(&mut message.kwargs);
        if let Some(extra) = &mut message.body_extra {
            self.normalize_json(extra);
        }
    }

    fn record(&mut self, rule: &str, why: &str) {
        self.applied
            .entry(rule.to_string())
            .or_insert_with(|| why.to_string());
    }
}

fn apply_string_mode(mode: ValueMode, value: &str) -> String {
    match mode {
        ValueMode::Volatile => "<volatile>".to_string(),
        ValueMode::VolatileIfNonEmpty => {
            if value.is_empty() {
                String::new()
            } else {
                "<volatile>".to_string()
            }
        }
        ValueMode::PasswordPrefix => password_marker(value),
        ValueMode::RandomColor => {
            if is_hex_color(value) {
                "<colour>".to_string()
            } else {
                value.to_string()
            }
        }
        // Relative timestamps and Unix times need the step window, so they
        // are handled by the caller before this function is reached.
        ValueMode::RelativeTime | ValueMode::UnixTime => value.to_string(),
    }
}

fn apply_json_mode(mode: ValueMode, value: &mut Value) {
    match mode {
        ValueMode::Volatile => {
            *value = Value::String("<volatile>".to_string());
        }
        ValueMode::VolatileIfNonEmpty => {
            let empty = match &value {
                Value::Null => true,
                Value::String(text) => text.is_empty(),
                _ => false,
            };
            if !empty {
                *value = Value::String("<volatile>".to_string());
            }
        }
        ValueMode::PasswordPrefix => {
            if let Value::String(text) = value {
                *text = password_marker(text);
            }
        }
        ValueMode::RandomColor => {
            if let Value::String(text) = value
                && is_hex_color(text)
            {
                *text = "<colour>".to_string();
            }
        }
        ValueMode::RelativeTime | ValueMode::UnixTime => {}
    }
}

fn password_marker(value: &str) -> String {
    if value.is_empty() {
        return String::new();
    }
    let mut parts = value.split('$');
    match (parts.next(), parts.next()) {
        (Some(algorithm), Some(iterations)) if algorithm != "!" => {
            format!("{algorithm}${iterations}$<hash>")
        }
        _ => "<password>".to_string(),
    }
}

fn dash_uuid(hex: &str) -> Option<String> {
    if hex.len() != 32 || !hex.chars().all(|c| c.is_ascii_hexdigit()) {
        return None;
    }
    Some(format!(
        "{}-{}-{}-{}-{}",
        &hex[0..8],
        &hex[8..12],
        &hex[12..16],
        &hex[16..20],
        &hex[20..32]
    ))
}

fn is_hex_color(value: &str) -> bool {
    value.len() == 7 && value.starts_with('#') && value[1..].chars().all(|c| c.is_ascii_hexdigit())
}

/// True when the response is JSON by its content type.
pub fn content_type_is_json(headers: &[(String, String)]) -> bool {
    headers
        .iter()
        .find(|(name, _)| name.eq_ignore_ascii_case("content-type"))
        .is_some_and(|(_, value)| {
            let media = value
                .split(';')
                .next()
                .unwrap_or_default()
                .trim()
                .to_ascii_lowercase();
            media == "application/json" || media.ends_with("+json")
        })
}

/// Collect every UUID that already exists in a baseline snapshot. Generated
/// ids are recognised as "not in this set".
pub fn collect_known_uuids(diffs: impl IntoIterator<Item = Value>) -> HashSet<String> {
    let mut uuids = HashSet::new();
    for value in diffs {
        collect_uuids_from(&value, &mut uuids);
    }
    uuids
}

fn collect_uuids_from(value: &Value, out: &mut HashSet<String>) {
    match value {
        Value::String(text) => {
            if is_uuid(text) {
                out.insert(text.to_ascii_lowercase());
            }
        }
        Value::Array(items) => {
            for item in items {
                collect_uuids_from(item, out);
            }
        }
        Value::Object(map) => {
            for value in map.values() {
                collect_uuids_from(value, out);
            }
        }
        _ => {}
    }
}

pub fn hex_encode(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push(HEX[(byte >> 4) as usize] as char);
        out.push(HEX[(byte & 0x0f) as usize] as char);
    }
    out
}

