//! Plane's outbound HTTP client: the SSRF guards of `plane/utils/url_security.py`
//! and `plane/utils/ip_address.py`, ported exactly, on top of `reqwest` +
//! `rustls`.
//!
//! The Python code these modules replace is the specification:
//!
//! * [`pyurl`] -- CPython 3.12's `urllib.parse` subset that decides which host
//!   is validated, with Python's error strings;
//! * [`ipaddr`] -- CPython 3.12's `ipaddress` properties and Plane's explicit
//!   deny-list, including IPv4-mapped, 6to4, Teredo and NAT64 decoding;
//! * [`ssrf`] -- allow lists, resolution of every address, the trusted-host
//!   exemption, and the two different validation orders (`validate_url` for
//!   create time, `validate_hop` for delivery time);
//! * [`client`] -- IP pinning through a fail-closed resolver, manual
//!   re-validating redirects, Python-compatible response text decoding;
//! * [`preset`] -- one entry per call site with the timeouts, headers, redirect
//!   policy, proxy policy and body caps that Python uses;
//! * [`dns`] -- the `getaddrinfo` seam plus a deterministic stub for tests.
//!
//! # Why pinning needs a custom resolver
//!
//! Python rewrites the URL to the validated IP literal, so urllib3 performs no
//! lookup. reqwest/rustls needs the SNI name to stay in the URL for certificate
//! verification, so [`HttpEngine`] keeps the name and installs a
//! [`dns::Resolver`]-backed reqwest resolver that answers only the pinned name.
//! A second lookup cannot happen: any other name fails the request.
//!
//! # Security invariants (each has a test)
//!
//! * every resolved address is validated, not only the first (fail closed on a
//!   dual-stack name with one internal answer);
//! * `WEBHOOK_ALLOWED_HOSTS` skips the block check but still resolves and pins;
//! * `WEBHOOK_ALLOWED_IPS` entries are `ip_network(strict=False)` networks;
//! * a redirect is never followed by the HTTP library; when a preset follows,
//!   every hop is re-resolved, re-validated and re-pinned;
//! * a DNS answer that changes between validation and connect cannot move the
//!   connection (`tests/live_https.rs`);
//! * ambient proxies are disabled for every pinned preset (a CONNECT tunnel
//!   would resolve the name at the proxy).
//!
//! # Verifying
//!
//! ```sh
//! cargo test -p plane-net
//! ```
//!
//! runs the golden corpus generated by `tools/net/ssrf_corpus.py` from the real
//! Python code (`tests/golden/ssrf_urls.jsonl`, 2 400 URL cases, and
//! `tests/golden/ssrf_ips.jsonl`, 6 835 address cases), the ported Django unit
//! tests, and the live HTTPS pinning test.

