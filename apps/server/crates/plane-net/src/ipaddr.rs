//! Python 3.12's `ipaddress` address classification, as used by
//! `plane/utils/ip_address.py`.
//!
//! Plane's SSRF guard does not ask "is this address global?"; it asks a
//! specific set of questions that changed between Python versions. This module
//! reproduces the answers of CPython **3.12.13** (the interpreter in
//! `apps/api/.venv`; the brief says 3.12.16 -- re-generate the corpus with the
//! pinned interpreter rather than trusting these tables):
//!
//! * `IPv4Address.is_private`    -- `_IPv4Constants._private_networks`, minus
//!   the two exceptions in `_private_networks_exceptions`;
//! * `IPv4Address.is_loopback`   -- `127.0.0.0/8`;
//! * `IPv4Address.is_reserved`   -- `240.0.0.0/4`;
//! * `IPv4Address.is_link_local` -- `169.254.0.0/16`;
//! * `IPv4Address.is_multicast`  -- `224.0.0.0/4`;
//! * `IPv4Address.is_unspecified`-- `0.0.0.0/32`;
//! * the IPv6 equivalents, including the `ipv4_mapped` delegation that
//!   `CPython` performs inside every one of those properties;
//! * `ip.ipv4_mapped`, `ip.sixtofour`, `ip.teredo` and the NAT64 well-known
//!   prefix decode used by `_embedded_ipv4`.
//!
//! `plane/utils/ip_address.py:16` also lists an explicit deny-list
//! (`_BLOCKED_NETWORKS`) because some of these ranges are neither `is_private`
//! nor `is_global` on 3.12 (notably `100.64.0.0/10`). Both layers are ported:
//! dropping either would change verdicts.
//!
//! The golden corpus (`tests/golden/ssrf_ips.jsonl`, generated by
//! `tools/net/ssrf_corpus.py`) records each property separately as well as the
//! final `is_blocked_ip` answer for every sampled address, so a table typo
//! fails the build rather than silently changing which addresses are reachable.

use std::net::{IpAddr, Ipv4Addr, Ipv6Addr};
use std::sync::OnceLock;

/// One CIDR network, parsed on first use.
#[derive(Debug, Clone, Copy)]
struct Net {
    base: u128,
    prefix: u8,
    v6: bool,
}

impl Net {
    /// `ipaddress.ip_network(cidr, strict=False)`: host bits are masked away,
    /// which is the only mode Plane uses for `WEBHOOK_ALLOWED_IPS` and for its
    /// own tables.
    fn parse(cidr: &str, v6: bool) -> Self {
        let (addr, prefix) = cidr
            .split_once('/')
            .expect("table entries always carry a prefix");
        let prefix: u8 = prefix.parse().expect("prefix in range");
        let base = if v6 {
            let parsed: Ipv6Addr = addr.parse().expect("valid IPv6 literal");
            let bits = u128::from(parsed);
            truncate(bits, prefix, 128)
        } else {
            let parsed: Ipv4Addr = addr.parse().expect("valid IPv4 literal");
            u128::from(u32::from(parsed))
        };
        Self { base, prefix, v6 }
    }

    fn contains(&self, ip: IpAddr) -> bool {
        match (self.v6, ip) {
            (false, IpAddr::V4(v4)) => {
                truncate(u128::from(u32::from(v4)), self.prefix, 32) == self.base
            }
            (true, IpAddr::V6(v6)) => truncate(u128::from(v6), self.prefix, 128) == self.base,
            _ => false,
        }
    }
}

/// Mask `bits` to `prefix` bits within a `width`-bit address.
fn truncate(bits: u128, prefix: u8, width: u8) -> u128 {
    if prefix == 0 {
        return 0;
    }
    if prefix >= width {
        return bits;
    }
    let shift = u32::from(width - prefix);
    bits & (((1u128 << (width as u32 - shift)) - 1) << shift)
}

fn net_list(entries: &[&str], v6: bool) -> Vec<Net> {
    entries.iter().map(|entry| Net::parse(entry, v6)).collect()
}

fn any_contains(nets: &[Net], ip: IpAddr) -> bool {
    nets.iter().any(|net| net.contains(ip))
}

