const V4_PRIVATE: &[&str] = &[
    "0.0.0.0/8",
    "10.0.0.0/8",
    "127.0.0.0/8",
    "169.254.0.0/16",
    "172.16.0.0/12",
    "192.0.0.0/24",
    "192.0.0.170/31",
    "192.0.2.0/24",
    "192.168.0.0/16",
    "198.18.0.0/15",
    "198.51.100.0/24",
    "203.0.113.0/24",
    "240.0.0.0/4",
    "255.255.255.255/32",
];

const V4_PRIVATE_EXCEPTIONS: &[&str] = &["192.0.0.9/32", "192.0.0.10/32"];

const V4_BLOCKED: &[&str] = &[
    "0.0.0.0/8",
    "100.64.0.0/10",
    "169.254.0.0/16",
    "255.255.255.255/32",
];

