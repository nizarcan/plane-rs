// IPv6 tables (`_IPv6Constants`)
// ---------------------------------------------------------------------------

const V6_PRIVATE: &[&str] = &[
    "::1/128",
    "::/128",
    // CPython prints this one as `::ffff:0.0.0.0/96`; `::ffff:0:0/96` is the
    // same network and parses in both languages.
    "::ffff:0:0/96",
    "64:ff9b:1::/48",
    "100::/64",
    "2001::/23",
    "2001:db8::/32",
    "2002::/16",
    "3fff::/20",
    "fc00::/7",
    "fe80::/10",
];

const V6_PRIVATE_EXCEPTIONS: &[&str] = &[
    "2001:1::1/128",
    "2001:1::2/128",
    "2001:3::/32",
    "2001:4:112::/48",
    "2001:20::/28",
    "2001:30::/28",
];

const V6_RESERVED: &[&str] = &[
    "::/8", "100::/8", "200::/7", "400::/6", "800::/5", "1000::/4", "4000::/3", "6000::/3",
    "8000::/3", "a000::/3", "c000::/3", "e000::/4", "f000::/5", "f800::/6", "fe00::/9",
];

const V6_BLOCKED: &[&str] = &[
    "::ffff:0:0/96",
    "64:ff9b::/96",
    "64:ff9b:1::/48",
    "2002::/16",
    "2001::/32",
    "fec0::/10",
];

struct Tables {
    v4_private: Vec<Net>,
    v4_private_exceptions: Vec<Net>,
    v4_blocked: Vec<Net>,
    v6_private: Vec<Net>,
    v6_private_exceptions: Vec<Net>,
    v6_reserved: Vec<Net>,
    v6_blocked: Vec<Net>,
}

fn tables() -> &'static Tables {
    static TABLES: OnceLock<Tables> = OnceLock::new();
    TABLES.get_or_init(|| Tables {
        v4_private: net_list(V4_PRIVATE, false),
        v4_private_exceptions: net_list(V4_PRIVATE_EXCEPTIONS, false),
        v4_blocked: net_list(V4_BLOCKED, false),
        v6_private: net_list(V6_PRIVATE, true),
        v6_private_exceptions: net_list(V6_PRIVATE_EXCEPTIONS, true),
        v6_reserved: net_list(V6_RESERVED, true),
        v6_blocked: net_list(V6_BLOCKED, true),
    })
}

// ---------------------------------------------------------------------------
// Per-address properties
// ---------------------------------------------------------------------------

fn v4_is_private(ip: Ipv4Addr) -> bool {
    let tables = tables();
    let addr = IpAddr::V4(ip);
    any_contains(&tables.v4_private, addr) && !any_contains(&tables.v4_private_exceptions, addr)
}

fn v4_is_reserved(ip: Ipv4Addr) -> bool {
    // CPython: `self in _IPv4Constants._reserved_network` (240.0.0.0/4).
    (u32::from(ip) >> 28) == 0xF
}

fn v4_is_loopback(ip: Ipv4Addr) -> bool {
    ip.octets()[0] == 127
}

fn v4_is_link_local(ip: Ipv4Addr) -> bool {
    let octets = ip.octets();
    octets[0] == 169 && octets[1] == 254
}

fn v4_is_multicast(ip: Ipv4Addr) -> bool {
    (u32::from(ip) >> 28) == 0xE
}

fn v4_is_unspecified(ip: Ipv4Addr) -> bool {
    ip == Ipv4Addr::UNSPECIFIED
}

/// `IPv6Address.ipv4_mapped`: `(ip >> 32) == 0xFFFF`.
fn ipv4_mapped(ip: Ipv6Addr) -> Option<Ipv4Addr> {
    let bits = u128::from(ip);
    if (bits >> 32) != 0xFFFF {
        return None;
    }
    Some(Ipv4Addr::from((bits & 0xFFFF_FFFF) as u32))
}

/// `IPv6Address.sixtofour`: `(ip >> 112) == 0x2002`.
fn sixtofour(ip: Ipv6Addr) -> Option<Ipv4Addr> {
    let bits = u128::from(ip);
    if (bits >> 112) != 0x2002 {
        return None;
    }
    Some(Ipv4Addr::from(((bits >> 80) & 0xFFFF_FFFF) as u32))
}

/// `IPv6Address.teredo`: `(ip >> 96) == 0x20010000`, yielding
/// `(server_ipv4, client_ipv4)` where the client is the ones' complement of the
/// low 32 bits (CPython: `~self._ip & 0xFFFFFFFF`).
fn teredo(ip: Ipv6Addr) -> Option<(Ipv4Addr, Ipv4Addr)> {
    let bits = u128::from(ip);
    if (bits >> 96) != 0x2001_0000 {
        return None;
    }
    let server = Ipv4Addr::from(((bits >> 64) & 0xFFFF_FFFF) as u32);
    let client = Ipv4Addr::from((!bits & 0xFFFF_FFFF) as u32);
    Some((server, client))
}

/// The NAT64 well-known prefix `64:ff9b::/96` embeds the IPv4 address in the
/// low 32 bits. The local-use prefix `64:ff9b:1::/48` is blocked wholesale
/// instead (see `_embedded_ipv4`).
fn nat64_well_known(ip: Ipv6Addr) -> Option<Ipv4Addr> {
    let bits = u128::from(ip);
    if (bits >> 32) != 0x0064_ff9b_0000_0000_0000_0000 {
        return None;
    }
    Some(Ipv4Addr::from((bits & 0xFFFF_FFFF) as u32))
}

fn v6_is_private(ip: Ipv6Addr) -> bool {
    if let Some(mapped) = ipv4_mapped(ip) {
        return v4_is_private(mapped);
    }
    let tables = tables();
    let addr = IpAddr::V6(ip);
    any_contains(&tables.v6_private, addr) && !any_contains(&tables.v6_private_exceptions, addr)
}

fn v6_is_reserved(ip: Ipv6Addr) -> bool {
    if let Some(mapped) = ipv4_mapped(ip) {
        return v4_is_reserved(mapped);
    }
    any_contains(&tables().v6_reserved, IpAddr::V6(ip))
}

fn v6_is_link_local(ip: Ipv6Addr) -> bool {
    if let Some(mapped) = ipv4_mapped(ip) {
        return v4_is_link_local(mapped);
    }
    let bits = u128::from(ip);
    // fe80::/10
    (bits >> 118) == 0b11_1111_1010
}

fn v6_is_multicast(ip: Ipv6Addr) -> bool {
    if let Some(mapped) = ipv4_mapped(ip) {
        return v4_is_multicast(mapped);
    }
    ip.octets()[0] == 0xFF
}

fn v6_is_unspecified(ip: Ipv6Addr) -> bool {
    if let Some(mapped) = ipv4_mapped(ip) {
        return v4_is_unspecified(mapped);
    }
    u128::from(ip) == 0
}

fn v6_is_loopback(ip: Ipv6Addr) -> bool {
    if let Some(mapped) = ipv4_mapped(ip) {
        return v4_is_loopback(mapped);
    }
    u128::from(ip) == 1
}

/// The address properties `plane/utils/ip_address.py:78` ORs together.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct IpProperties {
    pub is_private: bool,
    pub is_loopback: bool,
    pub is_reserved: bool,
    pub is_link_local: bool,
    pub is_multicast: bool,
    pub is_unspecified: bool,
}

impl IpProperties {
    pub fn blocks(&self) -> bool {
        self.is_private
            || self.is_loopback
            || self.is_reserved
            || self.is_link_local
            || self.is_multicast
            || self.is_unspecified
    }
}

pub fn properties(ip: IpAddr) -> IpProperties {
    match ip {
        IpAddr::V4(v4) => IpProperties {
            is_private: v4_is_private(v4),
            is_loopback: v4_is_loopback(v4),
            is_reserved: v4_is_reserved(v4),
            is_link_local: v4_is_link_local(v4),
            is_multicast: v4_is_multicast(v4),
            is_unspecified: v4_is_unspecified(v4),
        },
        IpAddr::V6(v6) => IpProperties {
            is_private: v6_is_private(v6),
            is_loopback: v6_is_loopback(v6),
            is_reserved: v6_is_reserved(v6),
            is_link_local: v6_is_link_local(v6),
            is_multicast: v6_is_multicast(v6),
            is_unspecified: v6_is_unspecified(v6),
        },
    }
}

/// IPv4 addresses embedded in an IPv6 transition address, in `_embedded_ipv4`'s
/// order. A Teredo address yields two.
fn embedded_ipv4(ip: Ipv6Addr) -> impl Iterator<Item = Ipv4Addr> {
    let mut out: [Option<Ipv4Addr>; 4] = [None; 4];
    out[0] = ipv4_mapped(ip);
    out[1] = sixtofour(ip);
    if let Some((server, client)) = teredo(ip) {
        out[2] = Some(server);
        out[3] = Some(client);
    }
    // `_embedded_ipv4` decodes only the well-known NAT64 prefix; the local-use
    // prefix is rejected by `V6_BLOCKED` before recursion. The NAT64 prefix is
    // disjoint from the mapped/6to4/Teredo ones, so this never overwrites.
    if let Some(nat64) = nat64_well_known(ip) {
        out[3] = Some(nat64);
    }
    out.into_iter().flatten()
}

/// `plane.utils.ip_address.is_blocked_ip`.
///
/// Fails closed: an address is blocked if any of the six CPython properties
/// says so, if it falls in Plane's explicit deny-list, or if an IPv4 address
/// embedded in an IPv6 transition format is blocked.
pub fn is_blocked_ip(ip: IpAddr) -> bool {
    match ip {
        IpAddr::V4(v4) => {
            properties(ip).blocks() || any_contains(&tables().v4_blocked, IpAddr::V4(v4))
        }
        IpAddr::V6(v6) => {
            if properties(ip).blocks() || any_contains(&tables().v6_blocked, IpAddr::V6(v6)) {
                return true;
            }
            embedded_ipv4(v6).any(|mapped| is_blocked_ip(IpAddr::V4(mapped)))
        }
    }
}

/// Python's `ipaddress.ip_address` error, reproduced for the bracket check
/// (`urllib.parse._check_bracketed_host`): every failure carries the same
/// message, so the URL parser can surface it verbatim.
pub fn parse_python_ip(text: &str) -> Option<IpAddr> {
    if !text.contains('%') {
        return text.parse::<IpAddr>().ok();
    }
    // `IPv6Address._split_scope_id` in CPython 3.12: split at the *first* `%`,
    // the scope must be non-empty and must not contain another `%`. (3.13 added
    // the "scope must be numeric if it starts with a digit" rule; 3.12 does not
    // check it, so `fe80::1%1a` is accepted today.)
    let (addr, scope) = text.split_once('%')?;
    if scope.is_empty() || scope.contains('%') || !addr.contains(':') {
        return None;
    }
    addr.parse::<Ipv6Addr>().ok().map(IpAddr::V6)
}

