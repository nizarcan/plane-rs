//! The Django baseline and its upgrade guard (`plans/CUTOVER.md` §4).
//!
//! `plane-migrator` owns the `public` schema from the last Django migration on.
//! Three states are possible when it starts:
//!
//! * **fresh install** — `public` is empty and no marker exists: apply the
//!   embedded `pg_dump` in one transaction and insert the `django_migrations`
//!   rows it was taken with, so a rollback to the Python image still works;
//! * **upgrade** — `public.django_migrations` exists: its `(app, name)` set must
//!   equal the baseline's exactly. Missing rows mean the database is older than
//!   this binary and the Django migrator has to run first; extra rows mean the
//!   database is newer and this binary refuses to downgrade it;
//! * **already migrated** — `plane_jobs.meta.django_baseline` holds this
//!   binary's baseline id: only the idempotent `plane_jobs` DDL runs.
//!
//! A non-empty `public` without `django_migrations` is refused, never guessed
//! at. Everything runs under one session-level advisory lock, because
//! `restart: no` (`docker-compose.yml:91`) does not stop an operator from
//! starting two migrators.
//!
//! Django at the pinned commit (`PROGRESS.md:12`, `290383d7f9`) ends at
//! `db:0125_reset_project_deploy_board_identity` and
//! `license:0006_instance_is_current_version_deprecated`
//! (`apps/api/migrations_lockfile.txt:9-10`). The 66 `RunPython` steps are
//! per-row backfills over rows that already exist, so an empty database has
//! nothing for them to touch and the dump is structure-only; the upgrade path
//! never replays them because Django already applied them.

use std::collections::BTreeSet;

use tokio_postgres::Client;

/// The advisory lock every migrator takes: `hashtextextended('plane-migrator',
/// 0)` computed on PostgreSQL 15.7. A literal, so a second binary version
/// computes the same key.
pub const ADVISORY_LOCK_KEY: i64 = 982_486_585_344_315_709;

/// The schema-only dump of a fresh database migrated by Django at the pinned
/// commit, generated by `tools/schema/baseline.py`.
pub const BASELINE_SQL: &str = include_str!("../../../deploy/schema/baseline.sql");

/// The `(app, name)` rows the same `migrate` inserted, in application order.
pub const DJANGO_MIGRATIONS: &str = include_str!("../../../deploy/schema/django_migrations.txt");

/// `plane_jobs.meta.django_baseline`. A database this binary created carries
/// this exact value; a different one was created by another binary version and
/// is refused rather than mixed.
pub const BASELINE_ID: &str = "db:0125_reset_project_deploy_board_identity,license:0006_instance_is_current_version_deprecated";

/// What the migrator did. Printed by `main`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Outcome {
    /// Empty `public`: the baseline was applied in this run.
    FreshInstall { migrations: usize },
    /// `django_migrations` matched the baseline exactly.
    Upgrade { migrations: usize },
    /// The marker named this binary's baseline; only idempotent DDL ran.
    AlreadyCurrent,
}

/// Why the migrator refused to touch the database.
#[derive(Debug, thiserror::Error)]
pub enum SchemaError {
    #[error(transparent)]
    Postgres(#[from] tokio_postgres::Error),
    #[error(transparent)]
    Queue(#[from] plane_jobs::queue::QueueError),
    #[error(
        "the database has {missing} migration(s) this binary does not know: {examples}. \
         It is older than the pin; run Django's migrator first \
         (apps/api/bin/docker-entrypoint-migrator.sh:5, `python manage.py migrate`)"
    )]
    OlderThanBaseline { missing: usize, examples: String },
    #[error(
        "the database has {extra} migration(s) newer than this binary: {examples}. \
         Refusing to downgrade; use a plane-migrator that matches the database \
         (plans/CUTOVER.md §4, upgrade guard)"
    )]
    NewerThanBaseline { extra: usize, examples: String },
    #[error(
        "the public schema is not empty but has no django_migrations table; \
         refusing to guess. Create the database with plane-migrator or migrate it \
         with Django first (apps/api/bin/docker-entrypoint-migrator.sh:5)"
    )]
    NonEmptyWithoutMigrations,
    #[error(
        "plane_jobs.meta.django_baseline is {found:?} but this binary expects {expected:?}; \
         the database was created by another plane-migrator version"
    )]
    DifferentBaseline { found: String, expected: String },
}

/// Run the baseline state machine. Idempotent: a second call on the same
/// database is [`Outcome::AlreadyCurrent`] (or [`Outcome::Upgrade`] if the
/// marker was removed by hand) and touches no Django table.
pub async fn migrate(client: &mut Client) -> Result<Outcome, SchemaError> {
    // Session-level: held for the whole run, released by `unlock` or by the
    // connection closing. `pg_advisory_lock` waits for a competing migrator.
    client
        .query_one("SELECT pg_advisory_lock($1)", &[&ADVISORY_LOCK_KEY])
        .await?;
    let outcome = migrate_locked(client).await;
    // A failed run must still release the lock before the error is reported;
    // `main` then closes the connection, which would release it anyway.
    let _ = client
        .query_one("SELECT pg_advisory_unlock($1)", &[&ADVISORY_LOCK_KEY])
        .await;
    outcome
}

async fn migrate_locked(client: &mut Client) -> Result<Outcome, SchemaError> {
    let expected = expected_migrations();

    if let Some(found) = marker(client).await? {
        if found != BASELINE_ID {
            return Err(SchemaError::DifferentBaseline {
                found,
                expected: BASELINE_ID.to_string(),
            });
        }
        plane_jobs::migrate(client).await?;
        return Ok(Outcome::AlreadyCurrent);
    }

    let has_migrations = client
        .query_one(
            "SELECT to_regclass('public.django_migrations') IS NOT NULL",
            &[],
        )
        .await?
        .get::<_, bool>(0);
    if has_migrations {
        let actual = read_migrations(client).await?;
        let missing: Vec<String> = expected.difference(&actual).cloned().collect();
        if !missing.is_empty() {
            return Err(SchemaError::OlderThanBaseline {
                missing: missing.len(),
                examples: examples(&missing),
            });
        }
        let extra: Vec<String> = actual.difference(&expected).cloned().collect();
        if !extra.is_empty() {
            return Err(SchemaError::NewerThanBaseline {
                extra: extra.len(),
                examples: examples(&extra),
            });
        }
        plane_jobs::migrate(client).await?;
        write_marker(client).await?;
        return Ok(Outcome::Upgrade {
            migrations: expected.len(),
        });
    }

    if public_is_non_empty(client).await? {
        return Err(SchemaError::NonEmptyWithoutMigrations);
    }

    // A `CREATE DATABASE` copies `public` from template1, and the dump itself
    // starts with `CREATE SCHEMA public`; dropping the empty schema first is
    // what makes the dump apply unchanged.
    let transaction = client.transaction().await?;
    transaction
        .batch_execute("DROP SCHEMA IF EXISTS public CASCADE")
        .await?;
    transaction.batch_execute(BASELINE_SQL).await?;
    let statement = transaction
        .prepare("INSERT INTO public.django_migrations (app, name, applied) VALUES ($1, $2, now())")
        .await?;
    for (app, name) in parse_migrations(DJANGO_MIGRATIONS) {
        transaction.execute(&statement, &[&app, &name]).await?;
    }
    transaction.commit().await?;

    plane_jobs::migrate(client).await?;
    write_marker(client).await?;
    Ok(Outcome::FreshInstall {
        migrations: expected.len(),
    })
}

/// `plane_jobs.meta.django_baseline`, when `plane_jobs.meta` exists.
async fn marker(client: &Client) -> Result<Option<String>, SchemaError> {
    let exists = client
        .query_one("SELECT to_regclass('plane_jobs.meta') IS NOT NULL", &[])
        .await?
        .get::<_, bool>(0);
    if !exists {
        return Ok(None);
    }
    let row = client
        .query_opt(
            "SELECT value FROM plane_jobs.meta WHERE key = 'django_baseline'",
            &[],
        )
        .await?;
    Ok(row.map(|row| row.get(0)))
}

async fn write_marker(client: &Client) -> Result<(), SchemaError> {
    client
        .execute(
            "INSERT INTO plane_jobs.meta (key, value) VALUES ('django_baseline', $1) \
             ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value",
            &[&BASELINE_ID],
        )
        .await?;
    Ok(())
}

async fn read_migrations(client: &Client) -> Result<BTreeSet<String>, SchemaError> {
    let rows = client
        .query("SELECT app, name FROM public.django_migrations", &[])
        .await?;
    Ok(rows
        .iter()
        .map(|row| format!("{}\t{}", row.get::<_, String>(0), row.get::<_, String>(1)))
        .collect())
}

/// `pg_class` relations in `public`: tables, partitioned tables, views,
/// materialised views, sequences, foreign tables. An empty schema has none.
async fn public_is_non_empty(client: &Client) -> Result<bool, SchemaError> {
    let row = client
        .query_one(
            "SELECT EXISTS ( \
               SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace \
               WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p', 'v', 'm', 'S', 'f'))",
            &[],
        )
        .await?;
    Ok(row.get(0))
}

fn expected_migrations() -> BTreeSet<String> {
    parse_migrations(DJANGO_MIGRATIONS)
        .into_iter()
        .map(|(app, name)| format!("{app}\t{name}"))
        .collect()
}

fn parse_migrations(text: &str) -> Vec<(String, String)> {
    text.lines()
        .filter(|line| !line.trim().is_empty())
        .filter_map(|line| {
            let (app, name) = line.split_once('\t')?;
            Some((app.to_string(), name.to_string()))
        })
        .collect()
}

fn examples(items: &[String]) -> String {
    let mut sorted = items.to_vec();
    sorted.sort();
    let shown: Vec<String> = sorted.iter().take(5).cloned().collect();
    if sorted.len() > shown.len() {
        format!(
            "{} (+{} more)",
            shown.join(", "),
            sorted.len() - shown.len()
        )
    } else {
        shown.join(", ")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn baseline_files_are_embedded_and_parse() {
        let migrations = parse_migrations(DJANGO_MIGRATIONS);
        assert_eq!(migrations.len(), 167);
        assert!(BASELINE_SQL.contains("CREATE TABLE public.django_migrations"));
        assert!(BASELINE_SQL.contains("CREATE TABLE public.issues"));
        assert_eq!(
            migrations
                .iter()
                .rfind(|(app, _)| app == "db")
                .map(|(_, name)| name.as_str()),
            Some("0125_reset_project_deploy_board_identity")
        );
        assert_eq!(
            migrations
                .iter()
                .rfind(|(app, _)| app == "license")
                .map(|(_, name)| name.as_str()),
            Some("0006_instance_is_current_version_deprecated")
        );
    }

    #[test]
    fn baseline_id_names_the_leaf_migrations() {
        for leaf in BASELINE_ID.split(',') {
            let (app, name) = leaf.split_once(':').expect("app:name");
            let migrations = parse_migrations(DJANGO_MIGRATIONS);
            assert!(
                migrations
                    .iter()
                    .any(|(candidate_app, candidate_name)| candidate_app == app
                        && candidate_name == name),
                "{leaf} is not in the baseline's django_migrations rows"
            );
        }
    }

    #[test]
    fn compare_reports_missing_and_extra() {
        let mut actual = expected_migrations();
        actual.remove("db\t0125_reset_project_deploy_board_identity");
        actual.insert("db\t0126_future".to_string());
        let expected = expected_migrations();
        let missing: Vec<String> = expected.difference(&actual).cloned().collect();
        let extra: Vec<String> = actual.difference(&expected).cloned().collect();
        assert_eq!(
            missing,
            vec!["db\t0125_reset_project_deploy_board_identity"]
        );
        assert_eq!(extra, vec!["db\t0126_future"]);
    }
}
